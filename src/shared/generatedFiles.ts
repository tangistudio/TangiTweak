/**
 * Support files folder sync keeps in the scripts folder for VS Code:
 * tt-api.d.ts (typings), tsconfig.json, package.json, eslint.config.mjs and
 * settings.schema.json, plus the package imports' and the built-in modules'
 * (valtio, React) typings under .tangitweak/types/, the SDK (the npm package
 * `tangitweak`, as this build made it) under .tangitweak/sdk/tangitweak/, and
 * the Editor's own checks as an ESLint plugin (.tangitweak/eslint-plugin.mjs).
 * TangiTweak owns them:
 * they are rewritten whenever sync starts (every browser start and
 * extension update) if their content differs, so edits don't stick.
 */
import { ALL_BUILTINS, builtinPaths, builtinSpecIn } from "./builtinSpecs";
import { isUrlSpec, NAME, PACKAGE_ORIGIN, packagePaths, packageUrlCore, TYPINGS_ROOT } from "./packageImports";
import { NO_SITE_STORE, SITE_NO_HANDLES, SITE_NO_STORES } from "./remote";
import { scriptLintCore, shortcutKeyNames, shortcutShapeProblem, type LintRule } from "./scriptLint";

/** the built-in modules' typings in the scripts folder (lib/builtin-types.json keys go under it) */
export const BUILTIN_TYPINGS_ROOT = `${TYPINGS_ROOT}/builtin`;
/** the SDK, the same files as the npm package `tangitweak` (lib/tangitweak-sdk.json keys go under it): the root package.json links it, so `npm install` gives tweaks `tangitweak/test` and makes their `"extends": "tangitweak/tsconfig.json"` resolve */
export const SDK_ROOT = ".tangitweak/sdk/tangitweak";
/** where the SDK keeps the built-ins' typings its tsconfig.json maps valtio and React to */
export const SDK_BUILTIN_TYPINGS = "types/builtin";
/** where Folder Sync wrote `@tangitweak/test` before 0.40.0-alpha: the folder and its package.json entries go */
export const OLD_TEST_PKG_ROOT = ".tangitweak/test";

export const API_DTS_FILE = "tt-api.d.ts";
export const TSCONFIG_FILE = "tsconfig.json";
export const PACKAGE_JSON_FILE = "package.json";
export const ESLINT_PLUGIN_FILE = ".tangitweak/eslint-plugin.mjs";
export const ESLINT_CONFIG_FILE = "eslint.config.mjs";

export const GENERATED_NOTE = "Auto-generated by TangiTweak: changing this file has no effect (TangiTweak ignores edits here and overwrites it on folder sync).";

/** the extension's typings with the do-not-edit header */
export const apiDtsText = (dts: string): string => `// ${GENERATED_NOTE}\n\n${dts}`;

const isPlainObj = (v: unknown): v is Record<string, any> => !!v && typeof v === "object" && !Array.isArray(v);

/**
 * package.json in the synced folder: marks ES modules, links the SDK
 * (`tangitweak`, with `tangitweak/test`), lists what eslint.config.mjs needs
 * (`npm install` once; typescript-eslint 8 wants TypeScript below 6.1), and
 * preserves user `scripts` / `dependencies` / `devDependencies` for local tests.
 */
export function packageJsonText(existing?: Record<string, any>): string {
    const prev = isPlainObj(existing) ? existing : {};
    const imports = { ...(isPlainObj(prev.imports) ? prev.imports : {}) };
    const devDeps = { ...(isPlainObj(prev.devDependencies) ? prev.devDependencies : {}) };
    if (imports["#tangitweak/test"] === `./${OLD_TEST_PKG_ROOT}/index.mjs`) delete imports["#tangitweak/test"];
    if (devDeps["@tangitweak/test"] === `file:${OLD_TEST_PKG_ROOT}`) delete devDeps["@tangitweak/test"];
    return (
        JSON.stringify(
            {
                ...prev,
                $comment: `${GENERATED_NOTE} User scripts/devDependencies for local tests are kept; TangiTweak scripts import runtime packages by pinned unpkg URL (https://unpkg.com/pkg@x.y.z). Run \`npm install\` once to lint tweaks with ESLint (eslint.config.mjs).`,
                private: typeof prev.private === "boolean" ? prev.private : true,
                type: "module",
                imports: Object.keys(imports).length ? imports : undefined,
                devDependencies: {
                    eslint: "^10.0.0",
                    typescript: "~6.0.0",
                    "typescript-eslint": "^8.0.0",
                    tangitweak: `file:${SDK_ROOT}`,
                    ...devDeps,
                },
            },
            null,
            2
        ) + "\n"
    );
}

const baseCompilerOptions = {
    target: "esnext",
    lib: ["esnext", "dom", "dom.iterable"],
    // tt-api.d.ts declares web APIs (URLPattern…) that newer TS libs may also have
    skipLibCheck: true,
    module: "esnext",
    moduleResolution: "bundler",
    allowImportingTsExtensions: true,
    // `import x from "./mock/data.json"` (data files)
    resolveJsonModule: true,
    // .tsx files: the automatic runtime, the built-in React by default
    jsx: "react-jsx",
    noEmit: true,
};

/**
 * Two of the SDK's files, for the npm package and Folder Sync alike (the
 * build makes the rest, scripts/build.mjs): the `tangitweak` module's
 * typings and the tsconfig.json a tweak's own extends.
 */
export function sdkFiles(dts: string): Record<string, string> {
    const tsconfig = {
        compilerOptions: {
            ...baseCompilerOptions,
            // relative to this file: the built-ins' typings the SDK ships, so tweaks see TangiTweak's own valtio and React
            paths: builtinPaths(`./${SDK_BUILTIN_TYPINGS}`),
        },
    };
    return {
        "index.d.ts": apiDtsText(dts),
        "tsconfig.json": `// ${GENERATED_NOTE}\n${JSON.stringify(tsconfig, null, 2)}\n`,
    };
}

/** tsconfig.json (TypeScript and VS Code read it as JSON with comments) */
export function tsconfigText(): string {
    const config = {
        compilerOptions: {
            ...baseCompilerOptions,
            // the SDK's test API, package imports (`https://unpkg.com/x@1.2.3`) → their downloaded typings
            // and the built-ins (`valtio`, `react`, `react-dom/client`…) → the extension's typings of them
            paths: {
                "tangitweak/test": [`./${SDK_ROOT}/test.d.ts`],
                ...packagePaths(`./${TYPINGS_ROOT}`),
                ...builtinPaths(`./${BUILTIN_TYPINGS_ROOT}`),
            },
        },
        include: ["**/*.ts", "**/*.tsx"],
    };
    return `// ${GENERATED_NOTE}\n${JSON.stringify(config, null, 2)}\n`;
}

/**
 * Every check the Editor marks as TangiTweak's, as an ESLint rule (with its
 * level in the recommended config). Adding a LintRule fails to compile here
 * until the plugin has it too. The Editor's "JSX needs a .tsx file" marker
 * has no rule: the TypeScript parser already rejects JSX in a .ts file.
 */
export const ESLINT_RULES = {
    "no-invalid-world-access": { level: "error", description: "onSite handlers can't use stores or handles; network handlers can't use tweak.siteStore" },
    "no-rules-side-effects": { level: "warn", description: 'code in strategy "rules" handlers runs once, not for each request' },
    "valid-selectors-and-shortcuts": { level: "error", description: "static selectors and shortcut keys must be valid" },
    "valid-package-imports": { level: "error", description: "URL imports must be pinned unpkg URLs (or the built-in React and valtio)" },
} satisfies Record<LintRule | "valid-package-imports", { level: "error" | "warn"; description: string }>;

/** eslint.config.mjs: TangiTweak's checks on the scripts, parsed by typescript-eslint */
export function eslintConfigText(): string {
    return `// ${GENERATED_NOTE}
//
// Lints the scripts with the checks TangiTweak's Editor shows. Run \`npm install\` once in
// this folder; then \`npx eslint .\`, or VS Code's ESLint extension, picks it up.

import tseslint from "typescript-eslint";
import tangitweak from "./.tangitweak/eslint-plugin.mjs";

export default [
    { ignores: ["node_modules/", ".tangitweak/", ".tangitweak-backup/", "**/*.d.ts"] },
    {
        ...tangitweak.configs.recommended,
        files: ["**/*.ts", "**/*.tsx"],
        languageOptions: { ...tangitweak.configs.recommended.languageOptions, parser: tseslint.parser },
    },
];
`;
}

/**
 * The Editor's checks as a self-contained ESLint (flat config) plugin for
 * external editors: the same rule code (scriptLintCore's, packageUrlCore's
 * and builtinSpecIn's source), with shortcut keys checked by their shape
 * (shortcutShapeProblem) instead of parseShortcut.
 */
export function eslintPluginText(): string {
    return `// ${GENERATED_NOTE}
//
// TangiTweak's script checks as an ESLint plugin (the Editor runs the same ones).
// eslint.config.mjs, next to the scripts, turns it on.

const env = {
    SITE_NO_STORES: ${JSON.stringify(SITE_NO_STORES)},
    SITE_NO_HANDLES: ${JSON.stringify(SITE_NO_HANDLES)},
    NO_SITE_STORE: ${JSON.stringify(NO_SITE_STORE)},
    shortcutProblem: (keys) => (${shortcutShapeProblem.toString()})(keys, ${JSON.stringify(shortcutKeyNames())}),
};

const core = (${scriptLintCore.toString()})(env);

const isUrlSpec = ${isUrlSpec.toString()};
const builtinSpecIn = ${builtinSpecIn.toString()};
const packageUrlCore = ${packageUrlCore.toString()};
const BUILTINS = ${JSON.stringify(ALL_BUILTINS)};

/** why a URL import can't load, or null (bare and relative imports are the TypeScript checker's) */
function importProblem(spec) {
    if (!isUrlSpec(spec) || builtinSpecIn(spec, BUILTINS)) return null;
    const r = packageUrlCore(spec, ${JSON.stringify(PACKAGE_ORIGIN)}, ${JSON.stringify(NAME)});
    return typeof r === "string" ? r : null;
}

const analyses = new WeakMap();
function diagnosticsOf(context) {
    const sourceCode = context.sourceCode ?? context.getSourceCode();
    let found = analyses.get(sourceCode.ast);
    if (!found) {
        found = core.diagnostics(core.analyze(sourceCode.ast, sourceCode.scopeManager));
        analyses.set(sourceCode.ast, found);
    }
    return found;
}

const ruleInfo = ${JSON.stringify(ESLINT_RULES, null, 4)};

function lintCreate(name) {
    return (context) => ({
        "Program:exit"() {
            for (const d of diagnosticsOf(context)) {
                if (d.rule !== name) continue;
                if (d.node && d.node.loc) context.report({ node: d.node, message: d.message });
                else context.report({ loc: { line: d.line, column: 0 }, message: d.message });
            }
        },
    });
}

function importsCreate(context) {
    const check = (node) => {
        if (!node || node.type !== "Literal" || typeof node.value !== "string") return;
        const message = importProblem(node.value);
        if (message) context.report({ node, message });
    };
    return {
        ImportDeclaration: (n) => check(n.source),
        ExportNamedDeclaration: (n) => check(n.source),
        ExportAllDeclaration: (n) => check(n.source),
        ImportExpression: (n) => check(n.source),
        CallExpression: (n) => {
            if (n.callee.type === "Identifier" && n.callee.name === "require") check(n.arguments[0]);
        },
    };
}

const rules = Object.fromEntries(
    Object.entries(ruleInfo).map(([name, { level, description }]) => [
        name,
        {
            meta: { type: level === "warn" ? "suggestion" : "problem", docs: { description }, schema: [] },
            create: name === "valid-package-imports" ? importsCreate : lintCreate(name),
        },
    ])
);

const plugin = { meta: { name: "tangitweak" }, rules, configs: {} };
plugin.configs.recommended = {
    plugins: { tangitweak: plugin },
    languageOptions: { sourceType: "module" },
    rules: Object.fromEntries(Object.entries(ruleInfo).map(([name, { level }]) => ["tangitweak/" + name, level])),
};

export default plugin;
`;
}
